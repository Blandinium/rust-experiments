use dashmap::DashMap;
use std::any::Any;
use std::collections::VecDeque;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::mpsc::{self, Receiver, Sender};
use std::sync::{Arc, Condvar, Mutex, Weak};
use std::thread::{self, JoinHandle};
use std::time::{Duration, Instant};

/// A trait for actors that need to hold a handle to themselves and the stage.
///
/// This trait is automatically implemented when using the `#[actor]` macro.
pub trait StageAware {
    /// Sets the handle for the actor. This is called by the stage during actor creation.
    fn set_handle(&mut self, handle: ActorHandle);
}

/// A unique identifier for an actor within a [`Stage`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ActorRef(pub u64);

/// Contextual information for a message being processed.
#[derive(Debug, Clone, Copy)]
pub struct MsgCtx {
    /// The reference of the sender actor, if any.
    pub from: Option<ActorRef>,
    /// The reference of the recipient actor (the current actor).
    pub to: ActorRef,
}

/// The result of an actor's message processing or initialization.
#[derive(Debug)]
pub enum ActorResult<S> {
    /// Processing succeeded, and the actor should continue with the new state.
    Ok(S),
    /// The actor should stop processing messages and be removed from the stage.
    Stop,
    /// An error occurred during processing; the actor will be stopped.
    Error(String),
}

/// A trait to facilitate converting types into [`ActorResult`].
///
/// Automatically implemented for `S` and `ActorResult<S>`.
pub trait ToActorResult<S> {
    /// Converts `self` into an [`ActorResult<S>`].
    fn to_actor_result(self) -> ActorResult<S>;
}

impl<S> ToActorResult<S> for S {
    fn to_actor_result(self) -> ActorResult<S> {
        ActorResult::Ok(self)
    }
}

impl<S> ToActorResult<S> for ActorResult<S> {
    fn to_actor_result(self) -> ActorResult<S> {
        self
    }
}

/// A trait that can handle any message by downcasting.
///
/// This trait is internal to the framework and should not be implemented directly.
pub trait AnyActor: Send + Sync {
    fn consume_any_message(&self, msg: Box<dyn Any + Send>, ctx: MsgCtx, state: Box<dyn Any + Send + Sync>) -> ActorResult<Box<dyn Any + Send + Sync>>;
    fn init_any(&self, param: Box<dyn Any + Send>) -> ActorResult<Box<dyn Any + Send + Sync>>;
}

/// The core Actor trait.
///
/// Implementors of this trait define how they handle messages and initialization.
/// Usually, this trait is implemented automatically via the `#[actor]` macro.
///
/// - `S`: The Actor's internal state type.
/// - `M`: The message type that this actor handles (typically an enum generated by the macro).
/// - `I`: The initialization parameter type.
pub trait Actor: AnyActor
where
    Self::M: Any + Send,
    Self::S: Any + Send + Sync,
    Self::I: Any + Send,
{
    /// The Actor's internal state type.
    type S;
    /// The message type that this actor handles.
    type M;
    /// The initialization parameter type.
    type I;

    /// Processes a single message.
    fn consume_message(&self, msg: Box<Self::M>, ctx: MsgCtx, state: Self::S) -> ActorResult<Self::S>;
    /// Initializes the actor's state.
    fn handle_init(&self, param: Self::I) -> ActorResult<Self::S>;
}

impl<A> AnyActor for A
where
    A: Actor + Send + Sync,
    A::M: Any + Send,
    A::S: Any + Send + Sync,
    A::I: Any + Send,
{
    fn consume_any_message(&self, msg: Box<dyn Any + Send>, ctx: MsgCtx, state: Box<dyn Any + Send + Sync>) -> ActorResult<Box<dyn Any + Send + Sync>> {
        let msg = msg.downcast::<A::M>().expect("invalid message type for actor");
        let state = state.downcast::<A::S>().expect("invalid state type for actor");
        match self.consume_message(msg, ctx, *state) {
            ActorResult::Ok(s) => ActorResult::Ok(Box::new(s)),
            ActorResult::Stop => ActorResult::Stop,
            ActorResult::Error(e) => ActorResult::Error(e),
        }
    }

    fn init_any(&self, param: Box<dyn Any + Send>) -> ActorResult<Box<dyn Any + Send + Sync>> {
        let param = param.downcast::<A::I>().expect("invalid initialization parameter for actor");
        match self.handle_init(*param) {
            ActorResult::Ok(s) => ActorResult::Ok(Box::new(s)),
            ActorResult::Stop => ActorResult::Stop,
            ActorResult::Error(e) => ActorResult::Error(e),
        }
    }
}

type ActorMessage = (Box<dyn Any + Send>, MsgCtx);
type ActorQueue = Arc<Mutex<VecDeque<(ActorRef, Receiver<ActorMessage>, ActorMessage)>>>;

/// A `Stage` manages a set of actors and schedules their message processing
/// across a fixed pool of worker threads.
///
/// It provides batching of messages to improve throughput and allows
/// actors to be added and signaled for shutdown.
///
/// # Examples
///
/// ```
/// use actrs::Stage;
/// use std::time::Duration;
///
/// let stage = Stage::new(4, 100, Duration::from_millis(10));
/// // add actors, send messages...
/// stage.shutdown();
/// ```
pub struct Stage {
    actors: DashMap<ActorRef, Arc<dyn AnyActor>>,
    states: DashMap<ActorRef, Box<dyn Any + Send + Sync>>,
    unqueued: DashMap<ActorRef, Mutex<Receiver<ActorMessage>>>,
    senders: DashMap<ActorRef, Sender<ActorMessage>>,
    queue: ActorQueue,
    next_id: AtomicU64,
    max_batch_messages: usize,
    max_batch_time: Duration,
    shutdown_flag: Arc<AtomicBool>,
    worker_threads: Mutex<Vec<JoinHandle<()>>>,
    work_condvar: Condvar,
    empty_condvar: Condvar,
}

impl Stage {
    /// Creates a new `Stage` with the specified configuration.
    ///
    /// - `num_threads`: Number of worker threads to spawn.
    /// - `max_batch_messages`: Maximum number of messages an actor processes in one batch.
    /// - `max_batch_time`: Maximum duration an actor processes in one batch.
    pub fn new(num_threads: usize, max_batch_messages: usize, max_batch_time: Duration) -> Arc<Self> {
        let queue = Arc::new(Mutex::new(VecDeque::new()));
        let shutdown_flag = Arc::new(AtomicBool::new(false));
        let stage_arc = Arc::new(Self {
            actors: DashMap::new(),
            states: DashMap::new(),
            unqueued: DashMap::new(),
            senders: DashMap::new(),
            queue: queue.clone(),
            next_id: AtomicU64::new(1),
            max_batch_messages,
            max_batch_time,
            shutdown_flag: shutdown_flag.clone(),
            worker_threads: Mutex::new(Vec::new()),
            work_condvar: Condvar::new(),
            empty_condvar: Condvar::new(),
        });

        let mut threads = Vec::new();
        for _ in 0..num_threads {
            let stage_clone = Arc::clone(&stage_arc);
            let shutdown_clone = shutdown_flag.clone();
            let handle = thread::spawn(move || loop {
                let next = {
                    let mut q = stage_clone.queue.lock().unwrap();
                    loop {
                        if shutdown_clone.load(Ordering::Relaxed) {
                            return;
                        }
                        if let Some(work) = q.pop_front() {
                            break Some(work);
                        }
                        q = stage_clone.work_condvar.wait(q).unwrap();
                    }
                };

                if let Some((actor_ref, receiver, (msg, ctx))) = next {
                    stage_clone.run_actor(actor_ref, receiver, msg, ctx);
                }
            });
            threads.push(handle);
        }

        {
            let mut worker_threads = stage_arc.worker_threads.lock().unwrap();
            *worker_threads = threads;
        }

        stage_arc
    }

    /// Returns the number of currently active actors in the stage.
    pub fn actor_count(&self) -> usize {
        self.actors.len()
    }

    /// Signals all worker threads to stop and joins them.
    ///
    /// This should be called once the stage is no longer needed.
    pub fn shutdown(&self) {
        self.shutdown_flag.store(true, Ordering::Relaxed);
        self.work_condvar.notify_all();
        let mut threads = self.worker_threads.lock().unwrap();
        for handle in threads.drain(..) {
            let _ = handle.join();
        }
    }

    /// Blocks the current thread until all actors in the stage have finished.
    pub fn wait_for_completion(&self) {
        let mut q = self.queue.lock().unwrap();
        while !self.actors.is_empty() {
            q = self.empty_condvar.wait(q).unwrap();
        }
    }

    fn run_actor(
        &self,
        actor_ref: ActorRef,
        receiver: Receiver<ActorMessage>,
        msg: Box<dyn Any + Send>,
        ctx: MsgCtx,
    ) {
        let actor = self.actors.get(&actor_ref).map(|a| a.value().clone());

        if let Some(actor) = actor {
            let state = self
                .states
                .remove(&actor_ref)
                .map(|(_, s)| s)
                .expect("actor state not found");

            let deadline = Instant::now() + self.max_batch_time;
            let mut processed = 0usize;
            let mut current_state = state;
            let mut current_msg = Some(msg);
            let mut current_ctx = ctx;

            while let Some(msg) = current_msg.take() {
                match actor.consume_any_message(msg, current_ctx, current_state) {
                    ActorResult::Ok(new_state) => {
                        current_state = new_state;
                        processed += 1;

                        if processed >= self.max_batch_messages || Instant::now() >= deadline {
                            break;
                        }

                        match receiver.try_recv() {
                            Ok((next_msg, next_ctx)) => {
                                current_msg = Some(next_msg);
                                current_ctx = next_ctx;
                            }
                            Err(_) => break,
                        }
                    }
                    ActorResult::Stop | ActorResult::Error(_) => {
                        self.actors.remove(&actor_ref);
                        self.senders.remove(&actor_ref);
                        if self.actors.is_empty() {
                            self.empty_condvar.notify_all();
                        }
                        return;
                    }
                }
            }

            self.states.insert(actor_ref, current_state);

            let hit_message_limit = processed >= self.max_batch_messages;
            let hit_time_limit = Instant::now() >= deadline;

            if hit_message_limit || hit_time_limit {
                self.queue_actor_if_pending(actor_ref, receiver);
            } else {
                self.return_to_unqueued(actor_ref, receiver);
            }
        }
    }

    fn queue_actor_if_pending(&self, actor_ref: ActorRef, receiver: Receiver<ActorMessage>) {
        if let Ok(msg_data) = receiver.try_recv() {
            self.queue.lock().unwrap().push_back((actor_ref, receiver, msg_data));
            self.work_condvar.notify_one();
        } else {
            self.return_to_unqueued(actor_ref, receiver);
        }
    }

    fn return_to_unqueued(&self, actor_ref: ActorRef, receiver: Receiver<ActorMessage>) {
        self.unqueued.insert(actor_ref, Mutex::new(receiver));
    }

    /// Sends a message to the specified actor.
    ///
    /// - `to`: Reference to the target actor.
    /// - `from`: Optional reference to the sender actor.
    /// - `msg`: The message to send.
    pub fn send(&self, to: ActorRef, from: Option<ActorRef>, msg: Box<dyn Any + Send>) {
        if let Some(sender) = self.senders.get(&to) {
            let _ = sender.send((msg, MsgCtx { from, to }));

            if let Some((_, receiver_mutex)) = self.unqueued.remove(&to) {
                let receiver = receiver_mutex.into_inner().unwrap();
                self.queue_actor_if_pending(to, receiver);
            }
        }
    }

    /// Adds a new actor to the stage and performs its initialization.
    ///
    /// The actor's `set_handle` is called before its `handle_init`.
    ///
    /// - `actor`: The actor instance.
    /// - `init_param`: The parameter passed to the actor's `handle_init`.
    ///
    /// Returns the actor's new `ActorRef`.
    pub fn add_actor<A>(self: &Arc<Self>, mut actor: A, init_param: A::I) -> ActorRef
where
    A: Actor + StageAware + 'static + Send + Sync,
{
        let id = self.next_id.fetch_add(1, Ordering::SeqCst);
        let actor_ref = ActorRef(id);
        let handle = ActorHandle::new(self, actor_ref);
        actor.set_handle(handle);
        
        match actor.handle_init(init_param) {
            ActorResult::Ok(initial_state) => {
                self.states.insert(actor_ref, Box::new(initial_state));
                self.actors.insert(actor_ref, Arc::new(actor));

                let (tx, rx) = mpsc::channel();
                self.senders.insert(actor_ref, tx);
                self.return_to_unqueued(actor_ref, rx);

                actor_ref
            }
            ActorResult::Stop | ActorResult::Error(_) => {
                // If initialization fails or requests stop, we don't add the actor.
                // We still return an ActorRef, but it will be dead.
                actor_ref
            }
        }
    }
}

/// A handle that allows an actor to interact with the stage and itself.
#[derive(Clone)]
pub struct ActorHandle {
    stage: Weak<Stage>,
    self_ref: ActorRef,
}

impl ActorHandle {
    /// Creates a new `ActorHandle`. This is primarily used internally by the stage.
    pub fn new(stage: &Arc<Stage>, self_ref: ActorRef) -> Self {
        Self {
            stage: Arc::downgrade(stage),
            self_ref,
        }
    }

    /// Returns the reference of the actor that owns this handle.
    pub fn self_ref(&self) -> ActorRef {
        self.self_ref
    }

    /// Sends a message to another actor on the same stage.
    ///
    /// # Errors
    /// Returns an error if the stage has been dropped.
    pub fn send(
        &self,
        to: ActorRef,
        msg: Box<dyn Any + Send>,
    ) -> Result<(), &'static str> {
        let stage = self.stage.upgrade().ok_or("stage no longer exists")?;
        stage.send(to, Some(self.self_ref), msg);
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::Duration;

    struct MyActor {
        _handle: Option<ActorHandle>,
    }

    impl MyActor {
        fn new() -> Self {
            Self { _handle: None }
        }
    }

    impl Actor for MyActor {
        type S = i32;
        type M = i32;
        type I = i32;

        fn consume_message(&self, msg: Box<i32>, _ctx: MsgCtx, state: i32) -> ActorResult<i32> {
            ActorResult::Ok(state + *msg)
        }

        fn handle_init(&self, param: i32) -> ActorResult<i32> {
            ActorResult::Ok(param)
        }
    }

    impl StageAware for MyActor {
        fn set_handle(&mut self, handle: ActorHandle) {
            self._handle = Some(handle);
        }
    }

    fn wait_for_state(stage: &Stage, actor_ref: ActorRef, expected: i32) {
        let deadline = Instant::now() + Duration::from_millis(500);

        loop {
            if let Some(state) = stage.states.get(&actor_ref) {
                if let Some(state) = state.downcast_ref::<i32>() {
                    if *state == expected {
                        return;
                    }
                }
            }

            if Instant::now() >= deadline {
                break;
            }

            let q = stage.queue.lock().unwrap();
            let _ = stage.empty_condvar.wait_timeout(q, Duration::from_millis(5)).unwrap();
        }

        let state = stage.states.get(&actor_ref).unwrap();
        let state = state.downcast_ref::<i32>().unwrap();
        assert_eq!(*state, expected);
    }

    #[test]
    fn test_stage_send_accumulates_messages() {
        let stage = Stage::new(2, 10, Duration::from_millis(10));
        let actor_ref = stage.add_actor(MyActor::new(), 0);

        stage.send(actor_ref, None, Box::new(10));
        stage.send(actor_ref, None, Box::new(20));

        wait_for_state(&stage, actor_ref, 30);
    }

    #[test]
    fn test_stage_batches_more_than_limit() {
        let stage = Stage::new(2, 10, Duration::from_millis(10));
        let actor_ref = stage.add_actor(MyActor::new(), 0);

        for _ in 0..11 {
            stage.send(actor_ref, None, Box::new(1));
        }

        wait_for_state(&stage, actor_ref, 11);
    }

    #[test]
    fn test_multiple_actors_unique_refs() {
        let stage = Stage::new(1, 10, Duration::from_millis(10));
        let ref1 = stage.add_actor(MyActor::new(), 0);
        let ref2 = stage.add_actor(MyActor::new(), 0);

        assert_ne!(ref1, ref2);
    }
}
